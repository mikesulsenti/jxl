//go:build amd64 && !noasm

#include "textflag.h"

#define KSEED 0
#define KABS  32
#define KINF  64
#define KMIN  96
#define KUP   128
#define KDOWN 160
#define KONE  192

// r = r * (4 - d*r*r*r) * third, with four in Y14 and a third in Y15.
#define NEWTON(D, R)       \
	VMULPD D, R, Y12   \
	VMULPD R, Y12, Y12 \
	VMULPD R, Y12, Y12 \
	VSUBPD Y12, Y14, Y12 \
	VMULPD Y12, R, R   \
	VMULPD Y15, R, R

// c = d*r*r, then c = (2*c + d/(c*c)) * third, leaving the root in R.
#define FINISH(D, R)         \
	VMULPD R, D, Y12     \
	VMULPD R, Y12, Y12   \
	VMULPD Y12, Y12, Y13 \
	VDIVPD Y13, D, Y13   \
	VADDPD Y12, Y12, Y11 \
	VADDPD Y13, Y11, Y12 \
	VMULPD Y15, Y12, R

// func cbrtAVX2(p *float32, n int, k *[7][8]float32)
TEXT ·cbrtAVX2(SB), NOSPLIT, $0-24
	MOVQ p+0(FP), SI
	MOVQ n+8(FP), CX
	MOVQ k+16(FP), AX

	MOVL         $0xAAAAAAAB, DX
	MOVQ         DX, X8
	VPBROADCASTD X8, Y8

	MOVQ         $0x4010000000000000, DX
	MOVQ         DX, X14
	VBROADCASTSD X14, Y14

	MOVQ         $0x3FD5555555555555, DX
	MOVQ         DX, X15
	VBROADCASTSD X15, Y15

loop:
	VMOVUPS (SI), Y0

	VANDPS KABS(AX), Y0, Y1
	VXORPS Y1, Y0, Y2

	VPXOR    Y3, Y3, Y3
	VPCMPEQD Y3, Y1, Y3
	VMOVUPS  KINF(AX), Y4
	VPCMPGTD Y4, Y1, Y5
	VPCMPEQD Y4, Y1, Y4
	VPOR     Y5, Y4, Y4
	VPOR     Y4, Y3, Y3

	VMOVUPS   KMIN(AX), Y4
	VPCMPGTD  Y1, Y4, Y4
	VMULPS    KUP(AX), Y1, Y5
	VBLENDVPS Y4, Y5, Y1, Y1

	VMOVUPS   KDOWN(AX), Y5
	VMOVUPS   KONE(AX), Y6
	VBLENDVPS Y4, Y5, Y6, Y5

	VPMULUDQ Y8, Y1, Y9
	VPSRLQ   $33, Y9, Y9
	VPSRLQ   $32, Y1, Y10
	VPMULUDQ Y8, Y10, Y10
	VPSRLQ   $33, Y10, Y10
	VPSLLQ   $32, Y10, Y10
	VPBLENDD $0xAA, Y10, Y9, Y9

	VMOVUPS KSEED(AX), Y10
	VPSUBD  Y9, Y10, Y9

	VCVTPS2PD X1, Y6
	VCVTPS2PD X9, Y13
	NEWTON(Y6, Y13)
	NEWTON(Y6, Y13)
	NEWTON(Y6, Y13)
	NEWTON(Y6, Y13)
	FINISH(Y6, Y13)
	VCVTPD2PSY Y13, X6

	VEXTRACTF128 $1, Y1, X7
	VEXTRACTF128 $1, Y9, X10
	VCVTPS2PD    X7, Y7
	VCVTPS2PD    X10, Y13
	NEWTON(Y7, Y13)
	NEWTON(Y7, Y13)
	NEWTON(Y7, Y13)
	NEWTON(Y7, Y13)
	FINISH(Y7, Y13)
	VCVTPD2PSY Y13, X7

	VINSERTF128 $1, X7, Y6, Y6

	VMULPS Y5, Y6, Y6
	VORPS  Y2, Y6, Y6

	VBLENDVPS Y3, Y0, Y6, Y6

	VMOVUPS Y6, (SI)

	ADDQ $32, SI
	SUBQ $8, CX
	JNZ  loop

	VZEROUPPER
	RET

#define KSEED5 0
#define KABS5  64
#define KINF5  128
#define KMIN5  192
#define KUP5   256
#define KDOWN5 320
#define KONE5  384

#define NEWTON5(D, R)      \
	VMULPD D, R, Z12   \
	VMULPD R, Z12, Z12 \
	VMULPD R, Z12, Z12 \
	VSUBPD Z12, Z14, Z12 \
	VMULPD Z12, R, R   \
	VMULPD Z15, R, R

#define FINISH5(D, R)        \
	VMULPD R, D, Z12     \
	VMULPD R, Z12, Z12   \
	VMULPD Z12, Z12, Z13 \
	VDIVPD Z13, D, Z13   \
	VADDPD Z12, Z12, Z11 \
	VADDPD Z13, Z11, Z12 \
	VMULPD Z15, Z12, R

// func cbrt512(p *float32, n int, k *[7][16]float32)
TEXT ·cbrt512(SB), NOSPLIT, $0-24
	MOVQ p+0(FP), SI
	MOVQ n+8(FP), CX
	MOVQ k+16(FP), AX

	MOVL         $0xAAAAAAAB, DX
	MOVQ         DX, X8
	VPBROADCASTD X8, Z8

	MOVL   $0xAAAA, DX
	KMOVW  DX, K3

	MOVQ         $0x4010000000000000, DX
	MOVQ         DX, X14
	VBROADCASTSD X14, Z14

	MOVQ         $0x3FD5555555555555, DX
	MOVQ         DX, X15
	VBROADCASTSD X15, Z15

loop512:
	VMOVUPS (SI), Z0

	VANDPS KABS5(AX), Z0, Z1
	VXORPS Z1, Z0, Z2

	VPXORD   Z3, Z3, Z3
	VPCMPEQD Z3, Z1, K1
	VMOVUPS  KINF5(AX), Z4
	VPCMPD   $5, Z4, Z1, K2
	KORW     K2, K1, K1

	VMOVUPS KMIN5(AX), Z4
	VPCMPD  $1, Z4, Z1, K2
	VMULPS  KUP5(AX), Z1, Z5
	VMOVAPS Z5, K2, Z1

	VMOVUPS KONE5(AX), Z5
	VMOVUPS KDOWN5(AX), Z6
	VMOVAPS Z6, K2, Z5

	VPMULUDQ  Z8, Z1, Z9
	VPSRLQ    $33, Z9, Z9
	VPSRLQ    $32, Z1, Z10
	VPMULUDQ  Z8, Z10, Z10
	VPSRLQ    $33, Z10, Z10
	VPSLLQ    $32, Z10, Z10
	VMOVDQA32 Z10, K3, Z9

	VMOVUPS KSEED5(AX), Z10
	VPSUBD  Z9, Z10, Z9

	VCVTPS2PD Y1, Z6
	VCVTPS2PD Y9, Z13
	NEWTON5(Z6, Z13)
	NEWTON5(Z6, Z13)
	NEWTON5(Z6, Z13)
	NEWTON5(Z6, Z13)
	FINISH5(Z6, Z13)
	VCVTPD2PS Z13, Y6

	VEXTRACTF64X4 $1, Z1, Y7
	VEXTRACTF64X4 $1, Z9, Y10
	VCVTPS2PD     Y7, Z7
	VCVTPS2PD     Y10, Z13
	NEWTON5(Z7, Z13)
	NEWTON5(Z7, Z13)
	NEWTON5(Z7, Z13)
	NEWTON5(Z7, Z13)
	FINISH5(Z7, Z13)
	VCVTPD2PS Z13, Y7

	VINSERTF64X4 $1, Y7, Z6, Z6

	VMULPS  Z5, Z6, Z6
	VORPS   Z2, Z6, Z6
	VMOVAPS Z0, K1, Z6

	VMOVUPS Z6, (SI)

	ADDQ $64, SI
	SUBQ $16, CX
	JNZ  loop512

	VZEROUPPER
	RET
